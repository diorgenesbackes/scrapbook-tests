import { expect, test, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { PNG } from 'pngjs'
import jsQR from 'jsqr'

const data = JSON.parse(readFileSync(process.env.SCRAPBOOK_IDENTIFICATION_MANIFEST!, 'utf8'))
const original = 'IC3_PRIVATE_GUEST_ANTERIOR_João'
const replacement = 'IC3_PRIVATE_GUEST_NOVO_José_🎉'
const key = (code = data.first.code) => `scrapbook.guest-identification.v1:${code}`
const path = (code = data.first.code) => `/e/${code}/identification`
const submit = (page: Page) => page.getByRole('button', { name: 'Confirmar identificação' })
async function identify(page: Page, code = data.first.code, name = original) {
  await page.goto(path(code))
  await expect(submit(page)).toBeEnabled()
  await page.getByRole('textbox').fill(name)
  await page.getByRole('checkbox').check()
  await submit(page).click()
  await expect(page.getByRole('heading', { name: 'Identificação confirmada' })).toBeFocused()
}
const stored = (page: Page, code = data.first.code) => page.evaluate(k => JSON.parse(localStorage.getItem(k)!), key(code))

test('confirmed A to B requires renewed consent and persists only a complete replacement', async ({ page }) => {
  await identify(page)
  await page.getByRole('button', { name: 'Alterar nome' }).click()
  await expect(page.getByRole('textbox')).toBeFocused()
  await page.getByRole('textbox').fill('  ' + replacement + '  ')
  await expect(page.getByRole('checkbox')).not.toBeChecked()
  await submit(page).click()
  await expect(page.getByRole('checkbox')).toBeFocused()
  expect((await stored(page)).name).toBe(original)
  await page.getByRole('checkbox').check()
  await submit(page).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Revise sua identificação' })).toBeVisible()
  await expect(page.getByRole('textbox')).toHaveValue(replacement)
  await expect(page.getByRole('checkbox')).toBeChecked()
  expect(await stored(page)).toEqual({ version: 1, eventCode: data.first.code, name: replacement, noticeCode: data.notice.code, consent: true })
})

test('A to B to A with accents stays unchecked and supports keyboard renewal at 320px and 200% text', async ({ page, browserName }, info) => {
  await identify(page)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Revise sua identificação' })).toBeVisible()
  await page.getByRole('checkbox').uncheck()
  await page.getByRole('button', { name: 'Alterar nome' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('textbox')).toBeFocused()
  await page.keyboard.insertText(replacement)
  await page.getByRole('textbox').selectText()
  await page.keyboard.insertText(original)
  await expect(page.getByRole('checkbox')).not.toBeChecked()
  await expect(page.getByRole('status').filter({ hasText: 'Concorde com o aviso para confirmar o nome em edição.' })).toBeVisible()
  await page.setViewportSize({ width: 320, height: 740 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: `artifacts/edit-identification-${info.project.name}-320-text200.png`, fullPage: true })
  const tab = browserName === 'webkit' ? 'Alt+Tab' : 'Tab'
  await page.keyboard.press(tab)
  await expect(page.getByRole('checkbox')).toBeFocused()
  await page.keyboard.press('Space')
  await page.keyboard.press(tab)
  await expect(submit(page)).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Identificação confirmada' })).toBeFocused()
})

