test('failed replacement preserves its draft for explicit retry or memory-only use', async ({ page }) => {
  await identify(page)
  await page.evaluate(() => {
    Reflect.set(globalThis, '__ic3SetItem', Storage.prototype.setItem)
    Storage.prototype.setItem = () => { throw new DOMException('Quota', 'QuotaExceededError') }
  })
  await page.getByRole('button', { name: 'Alterar nome' }).click()
  await page.getByRole('textbox').fill(replacement)
  await page.getByRole('checkbox').check()
  await submit(page).click()
  await expect(page.getByText(/Seu preenchimento foi mantido/)).toBeVisible()
  await expect(page.getByRole('textbox')).toHaveValue(replacement)
  await expect(page.getByRole('checkbox')).toBeChecked()
  expect((await stored(page)).name).toBe(original)
  await page.getByRole('button', { name: 'Cancelar alteração' }).click()
  await expect(page.getByRole('heading', { name: 'Identificação confirmada' })).toBeVisible()
  await page.getByRole('button', { name: 'Alterar nome' }).click()
  await page.getByRole('textbox').fill(replacement)
  await page.getByRole('checkbox').check()
  await submit(page).click()
  await page.evaluate(() => { Storage.prototype.setItem = Reflect.get(globalThis, '__ic3SetItem') })
  await page.getByRole('button', { name: 'Tentar salvar novamente' }).click()
  await expect(page.getByRole('heading', { name: 'Identificação confirmada' })).toBeVisible()
  expect((await stored(page)).name).toBe(replacement)
  await page.getByRole('button', { name: 'Alterar nome' }).click()
  await page.getByRole('textbox').fill(original)
  await page.getByRole('checkbox').check()
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('Quota', 'QuotaExceededError') } })
  await submit(page).click()
  await page.getByRole('button', { name: 'Usar apenas nesta página' }).click()
  await expect(page.getByText('Sua identificação está confirmada apenas nesta página.')).toBeVisible()
  await expect(page.getByText(/será recuperada a identificação anterior salva/)).toBeVisible()
  await page.reload()
  await expect(page.getByRole('textbox')).toHaveValue(replacement)
})

test('editing event A never changes B and ignores a delayed response after navigation', async ({ page }) => {
  await identify(page, data.second.code, 'Bia')
  await identify(page)
  let release: (() => void) | undefined
  const held = new Promise<void>(resolve => { release = resolve })
  await page.route(`**/api/v1/public/events/${data.first.code}/consent-notice`, async route => {
    await held
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify({ code: 'late', body: 'IC3_LATE_NOTICE' }) }).catch(() => {})
  })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('textbox').fill(replacement)
  await page.evaluate(code => { history.pushState(null, '', `/e/${code}/identification`); dispatchEvent(new PopStateEvent('popstate')) }, data.second.code)
  await expect(page.getByRole('textbox')).toHaveValue('Bia')
  release?.()
  await expect(page.getByText('IC3_LATE_NOTICE')).toHaveCount(0)
  await expect(page.getByRole('checkbox')).toBeChecked()
  expect((await stored(page)).name).toBe(original)
  expect((await stored(page, data.second.code)).name).toBe('Bia')
  await page.unroute(`**/api/v1/public/events/${data.first.code}/consent-notice`)
  await page.goto(path())
  await expect(page.getByRole('textbox')).toHaveValue(original)
})

test('previous and new names stay out of traffic, metadata, public presentation and QR exports', async ({ page }) => {
  const requests: unknown[] = [], consoleMessages: string[] = [], administrative: string[] = []
  page.on('request', request => requests.push({ url: request.url(), data: request.postData(), headers: request.headers() }))
  page.on('console', message => consoleMessages.push(message.text()))
  page.on('response', async response => {
    if (new URL(response.url()).pathname.startsWith('/api/v1/events')) administrative.push(await response.text())
  })
  await identify(page)
  await page.getByRole('button', { name: 'Alterar nome' }).click()
  await page.getByRole('textbox').fill(replacement)
  await page.getByRole('checkbox').check()
  await submit(page).click()
  expect(await page.title()).toBe('Identificação | Scrap Book')
  expect(await page.evaluate(() => JSON.stringify(history.state))).not.toContain('IC3_PRIVATE_GUEST')
  expect(requests.some(request => JSON.stringify(request).includes('/api/v1/events'))).toBe(false)
  await page.getByRole('link', { name: 'Voltar ao evento' }).click()
  await expect(page.getByRole('heading', { name: data.first.name })).toBeVisible()
  expect(await page.locator('body').textContent()).not.toContain('IC3_PRIVATE_GUEST')
  const decode = (bytes: Buffer) => {
    const png = PNG.sync.read(bytes)
    return jsQR(Uint8ClampedArray.from(png.data), png.width, png.height, { inversionAttempts: 'dontInvert' })?.data
  }
  const qr = page.getByRole('img', { name: 'QR code para abrir a página pública do evento.' })
  await expect(qr).toBeVisible()
  expect(decode(Buffer.from((await qr.getAttribute('src'))!.split(',')[1]!, 'base64'))).toBe(data.first.publicUrl)
  await page.goto(`/events/${data.first.id}/share`)
  await expect(page.getByRole('button', { name: 'Baixar PNG para compartilhar' })).toBeEnabled()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Baixar PNG para compartilhar' }).click()
  const download = await downloading
  expect(decode(readFileSync((await download.path())!))).toBe(data.first.publicUrl)
  expect(download.suggestedFilename()).not.toContain('IC3_PRIVATE_GUEST')
  expect(administrative.length).toBeGreaterThan(0)
  expect(JSON.stringify({ requests, administrative, consoleMessages })).not.toContain('IC3_PRIVATE_GUEST')
  expect(await page.locator('body').textContent()).not.toContain('IC3_PRIVATE_GUEST')
})
